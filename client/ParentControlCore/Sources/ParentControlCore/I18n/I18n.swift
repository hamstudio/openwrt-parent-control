    public init() {
        let saved = UserDefaults.standard.string(forKey: "parentcontrol_app_lang") ?? "auto"
        setLocale(saved)
    }

    public func setLocale(_ locale: String) {
        UserDefaults.standard.set(locale, forKey: "parentcontrol_app_lang")
        if locale == "auto" {
            let preferred = Locale.preferredLanguages.first ?? "zh"
            if preferred.hasPrefix("zh-Hant") || preferred.hasPrefix("zh-TW") || preferred.hasPrefix("zh-HK") {
                self.currentLocale = "zh-Hant"
            } else if preferred.hasPrefix("zh") {
                self.currentLocale = "zh"
            } else if preferred.hasPrefix("ja") {
                self.currentLocale = "ja"
            } else if preferred.hasPrefix("ko") {
                self.currentLocale = "ko"
            } else if preferred.hasPrefix("de") {
                self.currentLocale = "de"
            } else if preferred.hasPrefix("fr") {
                self.currentLocale = "fr"
            } else if preferred.hasPrefix("es") {
                self.currentLocale = "es"
            } else {
                self.currentLocale = "en"
            }
        } else {
            self.currentLocale = locale
        }
    }

    public func t(_ key: String) -> String {
        return strings[currentLocale]?[key] ?? strings["zh"]?[key] ?? key
    }
}

